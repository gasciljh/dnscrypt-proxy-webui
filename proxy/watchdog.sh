# when the watchdog token is available.
# ============================================================
BASE64_CMD=""
if command -v base64 >/dev/null 2>&1; then
    BASE64_CMD="base64"
elif command -v busybox >/dev/null 2>&1 && busybox --list 2>/dev/null | grep -q "^base64$"; then
    BASE64_CMD="busybox base64"
fi

# ============================================================
# [10] Explicit safe PATH
# ============================================================
SAFE_PATH="/sbin:/system/bin:/system/xbin:/vendor/bin:/data/adb/magisk:/data/adb/ksu/bin:/data/adb/ap/bin"

# ============================================================
# [11] API call helper
# ============================================================
# Uses POST /api/ensure_running_service for CSRF-GET protection.
#
# Authentication (WD-TOKEN fix):
#   1. X-Watchdog-Token header  — preferred
#   2. Authorization: Basic ... — fallback (only when no token)
#
# Return codes:
#   0 — success (2xx)
#   1 — no HTTP client available
#   2 — network/timeout failure
#   3 — 429 rate-limited (curl path only)
#   4 — other HTTP error, OR unable to determine the result
#
# BUG-A fix: temp files live under $RUN_DIR, not /tmp.
# BUG-B fix: empty http_code returns 4, not 0.
# WD-TOKEN fix: X-Watchdog-Token header is sent when available.
# HARD-WD-01: all working variables declared `local`.
#
# M-4 fix: the wget/busybox paths no longer attempt to parse
# HTTP status from `-qO-` output (which never contains the
# headers). They rely on the process exit code instead. This
# is the ONLY reliable signal available when `curl` is absent.
# ============================================================
watchdog_api_call() {
    local action="$1"
    local tool=""
    local wd_token=""
    local token_header=""
    local auth_header=""
    local b64=""
    local url=""
    local http_code=""
    local exit_code=0
    local tmp_resp=""
    local tmp_code=""
    local output=""

    if command -v curl >/dev/null 2>&1; then
        tool="curl"
    elif command -v wget >/dev/null 2>&1; then
        tool="wget"
    elif command -v busybox >/dev/null 2>&1; then
        tool="busybox"
    else
        log_msg "WARNING: no HTTP client available"
        return 1
    fi

    # --- Build X-Watchdog-Token header (WD-TOKEN fix — preferred) ---
    # M-3 fix: the helper writes nothing to stderr, and its
    # failure mode is "empty stdout". `|| :` makes that
    # explicit and avoids the redundant `2>/dev/null` that
    # suppressed nothing.
    wd_token=$(_wd_get_watchdog_token 2>/dev/null || :)
    if [ -n "$wd_token" ]; then
        token_header="X-Watchdog-Token: $wd_token"
    fi

    # --- Build Authorization header (fallback) ---
    # Only used when no token is available. This preserves the
    # previous behavior for the edge case where main.go has not
    # yet written the token file (very early boot).
    if [ -z "$wd_token" ] && [ "$HAS_CREDS" = "1" ] && [ -n "$BASE64_CMD" ]; then
        b64=$(printf "%s:%s" "$WATCH_USER" "$WATCH_PASS" | $BASE64_CMD 2>/dev/null | tr -d '\n')
        if [ -n "$b64" ]; then
            auth_header="Authorization: Basic $b64"
        fi
    fi

    # --- URL ---
    url="http://127.0.0.1:$PORT/api/${action}_service"

    case "$tool" in
        curl)
            # BUG-A fix: temp files under $RUN_DIR, not /tmp.
            tmp_resp="${RUN_DIR}/.wd_resp.$$"
            tmp_code="${RUN_DIR}/.wd_code.$$"

            # Build the argument list incrementally so we can send
            # zero, one, or two auth headers as appropriate.
            if [ -n "$token_header" ] && [ -n "$auth_header" ]; then
                env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    curl -s --noproxy '*' --max-time 5 \
                    -o "$tmp_resp" -w '%{http_code}' \
                    -X POST \
                    -H "$token_header" \
                    -H "$auth_header" "$url" \
                    > "$tmp_code" 2>/dev/null
            elif [ -n "$token_header" ]; then
                env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    curl -s --noproxy '*' --max-time 5 \
                    -o "$tmp_resp" -w '%{http_code}' \
                    -X POST \
                    -H "$token_header" \
                    "$url" \
                    > "$tmp_code" 2>/dev/null
            elif [ -n "$auth_header" ]; then
                env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    curl -s --noproxy '*' --max-time 5 \
                    -o "$tmp_resp" -w '%{http_code}' \
                    -X POST \
                    -H "$auth_header" "$url" \
                    > "$tmp_code" 2>/dev/null
            else
                env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    curl -s --noproxy '*' --max-time 5 \
                    -o "$tmp_resp" -w '%{http_code}' \
                    -X POST \
                    "$url" \
                    > "$tmp_code" 2>/dev/null
            fi
            exit_code=$?

            if [ -f "$tmp_code" ]; then
                http_code=$(cat "$tmp_code" 2>/dev/null | tr -d '\r\n ')
            fi
            rm -f "$tmp_resp" "$tmp_code" 2>/dev/null

            # --- Analyze curl result ---
            if [ "$exit_code" -ne 0 ]; then
                log_msg "WARNING: API call failed (exit=$exit_code) — network/timeout"
                return 2
            fi

            if [ -n "$http_code" ]; then
                case "$http_code" in
                    200|201|202|204)
                        log_msg "API call succeeded (HTTP $http_code)"
                        return 0
                        ;;
                    429)
                        log_msg "API rate-limited (HTTP 429) — backing off"
                        return 3
                        ;;
                    *)
                        log_msg "WARNING: API call returned HTTP $http_code"
                        return 4
                        ;;
                esac
            fi

            # BUG-B fix: no http_code + exit_code=0 is UNDECIDABLE.
            # Treat as error so the watchdog retries with backoff.
            log_msg "WARNING: API call returned no HTTP status code (undecidable) — treating as error"
            return 4
            ;;

        wget)
            # M-4 fix: `wget -qO-` does NOT print HTTP headers,
            # so `http_code` is always empty here. Rely on the
            # exit code instead.
            #
            # GNU wget exit codes (relevant subset):
            #   0 — success (2xx)
            #   8 — server error (4xx/5xx)  → return 4
            #   * — network/timeout/parse   → return 2
            #
            # A 429 cannot be distinguished in this path and
            # will be treated as a generic failure, which is
            # acceptable (backoff applies either way).
            if [ -n "$token_header" ] && [ -n "$auth_header" ]; then
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    --header="$token_header" \
                    --header="$auth_header" "$url" \
                    2>&1) || exit_code=$?
            elif [ -n "$token_header" ]; then
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    --header="$token_header" "$url" \
                    2>&1) || exit_code=$?
            elif [ -n "$auth_header" ]; then
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    --header="$auth_header" "$url" \
                    2>&1) || exit_code=$?
            else
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    "$url" \
                    2>&1) || exit_code=$?
            fi

            if [ "$exit_code" -eq 0 ]; then
                log_msg "API call succeeded (wget exit 0)"
                return 0
            fi
            if [ "$exit_code" -eq 8 ]; then
                log_msg "WARNING: API call returned HTTP error (wget exit 8)"
                return 4
            fi
            log_msg "WARNING: API call failed (wget exit=$exit_code) — network/timeout"
            return 2
            ;;

        busybox)
            # M-4 fix: same rationale as the wget path above.
            # BusyBox wget returns 0 on success and 1 on most
            # errors; it does not provide granular exit codes.
            # Therefore any non-zero result is reported as a
            # generic HTTP error (return 4), which still drives
            # the backoff correctly.
            if [ -n "$token_header" ] && [ -n "$auth_header" ]; then
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    busybox wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    --header="$token_header" \
                    --header="$auth_header" "$url" \
                    2>&1) || exit_code=$?
            elif [ -n "$token_header" ]; then
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    busybox wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    --header="$token_header" "$url" \
                    2>&1) || exit_code=$?
            elif [ -n "$auth_header" ]; then
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    busybox wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    --header="$auth_header" "$url" \
                    2>&1) || exit_code=$?
            else
                output=$(env -i PATH="$SAFE_PATH" HOME=/data/local/tmp \
                    http_proxy= https_proxy= HTTP_PROXY= HTTPS_PROXY= \
                    no_proxy= NO_PROXY= \
                    busybox wget -qO- --no-proxy --timeout=5 --tries=1 \
                    --post-data='' \
                    "$url" \
                    2>&1) || exit_code=$?
            fi

            if [ "$exit_code" -eq 0 ]; then
                log_msg "API call succeeded (busybox wget exit 0)"
                return 0
            fi
            log_msg "WARNING: API call failed (busybox wget exit=$exit_code) — HTTP or network error"
            return 4
            ;;
    esac

    # Unreachable — all three branches above return explicitly.
    return 4
}

# ============================================================
# [12] Exponential backoff
# ============================================================
# WD-2 fix: the reset-on-STATUS_FILE-change applies ONLY to
# DNS_BACKOFF_CURRENT. The WebUI has no equivalent concept of
# "user intent" — its backoff resets only on a successful
# restart.
#
# HARD-WD-05: BACKOFF_BASE is used as the MINIMUM sleep
# interval, not as the sleep duration. See section [13.0].
# ============================================================
BACKOFF_BASE=30
BACKOFF_MAX=600

WEBUI_BACKOFF_CURRENT=30
DNS_BACKOFF_CURRENT=30

# --- Previous DNS intent (to detect STATUS_FILE changes) ---
PREV_DESIRED=""

# ============================================================
# [13] Main loop
# ============================================================
log_msg "Entering main loop..."
LOOP_COUNT=0

# --- HARD-WD-05: per-service last-attempt timestamps ---
# These track the epoch of the last attempt for each service.
# A service is only re-attempted when its own backoff has
# elapsed since its last attempt. This decouples the two
# services: while DNS is being backed off to 600s, the WebUI
# continues to be checked every 30s, and vice versa.
LAST_WEBUI_ATTEMPT=0
LAST_DNS_ATTEMPT=0

# WD-1 fix: the `{ ... } 2>/dev/null` wrapper was a no-op
# (log_msg writes to a file, not stderr) and has been removed.
_profile_hint=$(_wd_get_profile_memory_hint)
log_msg "Active profile: $_profile_hint"

while true; do
    LOOP_COUNT=$((LOOP_COUNT + 1))

    # --- [13.0] Compute sleep (HARD-WD-05) ---
    # Sleep for min(webui_backoff, dns_backoff), floored at a
    # small sanity value so we do not busy-wait. Each service
    # will only be *attempted* when its own backoff has elapsed
    # since the last attempt (see [13.2] / [13.3]).
    SLEEP_DURATION="$WEBUI_BACKOFF_CURRENT"
    if [ "$DNS_BACKOFF_CURRENT" -lt "$SLEEP_DURATION" ]; then
        SLEEP_DURATION="$DNS_BACKOFF_CURRENT"
    fi
    [ "$SLEEP_DURATION" -lt 5 ] && SLEEP_DURATION=5
    [ "$SLEEP_DURATION" -gt "$BACKOFF_MAX" ] && SLEEP_DURATION="$BACKOFF_MAX"

    sleep "$SLEEP_DURATION"

    # --- [13.1] Check for disable ---
    if [ -f "$MODDIR/disable" ]; then
        log_msg "module disabled -> Watchdog exiting"
        rm -f "$WATCHDOG_PID_FILE" 2>/dev/null
        exit 0
    fi

    # HARD-WD-06: guard against empty `date` output.
    now=$(date +%s 2>/dev/null)
    case "$now" in
        ''|*[!0-9]*) now=0 ;;
    esac

    # ============================================================
    # [13.2] Restart WebUI
    # ============================================================
    # Only attempt when WEBUI_BACKOFF_CURRENT has elapsed since
    # LAST_WEBUI_ATTEMPT.
    #
    # M-2 fix: `_wd_cleanup_webui` is called exactly ONCE, here,
    # immediately before the start attempt. It is no longer
    # duplicated inside `_wd_start_webui`.
    if [ "$AUTO_RESTART_WEBUI" = "1" ]; then
        if [ $((now - LAST_WEBUI_ATTEMPT)) -ge "$WEBUI_BACKOFF_CURRENT" ]; then
            LAST_WEBUI_ATTEMPT="$now"

            if ! _wd_is_port_open "$PORT" tcp; then
                log_msg "WebUI down on port $PORT — restarting..."
                _wd_cleanup_webui
                sleep 1

                if _wd_start_webui "$WEBUI" "$PORT"; then
                    WEBUI_BACKOFF_CURRENT="$BACKOFF_BASE"
                else
                    WEBUI_BACKOFF_CURRENT=$((WEBUI_BACKOFF_CURRENT * 2))
                    [ "$WEBUI_BACKOFF_CURRENT" -gt "$BACKOFF_MAX" ] && WEBUI_BACKOFF_CURRENT="$BACKOFF_MAX"
                    log_msg "WARNING: WebUI restart failed — next attempt in ${WEBUI_BACKOFF_CURRENT}s"
                fi
            else
                # WebUI is running — reset backoff
                WEBUI_BACKOFF_CURRENT="$BACKOFF_BASE"
            fi
        fi
    fi

    # ============================================================
    # [13.3] Restart DNS Engine
    # ============================================================
    #
    # STATUS_FILE represents "user intent":
    #   * ON  = user wants the service running -> Watchdog restarts it
    #   * OFF = user stopped it manually -> Watchdog does nothing
    #
    # DNS_BACKOFF is independent from WEBUI_BACKOFF.
    # DNS backoff resets when STATUS_FILE changes (user changed
    # intent) — this is the only place STATUS_FILE affects backoff.
    #
    # Only attempt when DNS_BACKOFF_CURRENT has elapsed since
    # LAST_DNS_ATTEMPT.
    if [ "$AUTO_RESTART_DNS" = "1" ]; then
        desired="OFF"
        if [ -f "$STATUS_FILE" ]; then
            desired=$(cat "$STATUS_FILE" 2>/dev/null | tr -d '\r\n ')
        fi
        [ -z "$desired" ] && desired="OFF"

        # --- Detect intent change -> reset backoff ---
        if [ "$desired" != "$PREV_DESIRED" ]; then
            if [ -n "$PREV_DESIRED" ]; then
                log_msg "STATUS_FILE changed: $PREV_DESIRED -> $desired"
            fi
            PREV_DESIRED="$desired"
            DNS_BACKOFF_CURRENT="$BACKOFF_BASE"
        fi

        if [ "$desired" = "ON" ]; then
            if [ $((now - LAST_DNS_ATTEMPT)) -ge "$DNS_BACKOFF_CURRENT" ]; then
                LAST_DNS_ATTEMPT="$now"

                if ! _wd_is_port_open 5354 udp; then
                    # Wait a moment + re-check (it may have just started)
                    sleep 1
                    recheck="OFF"
                    if [ -f "$STATUS_FILE" ]; then
                        recheck=$(cat "$STATUS_FILE" 2>/dev/null | tr -d '\r\n ')
                    fi

                    if [ "$recheck" != "ON" ]; then
                        log_msg "status changed to $recheck during check — skipping restart"
                        PREV_DESIRED="$recheck"
                        DNS_BACKOFF_CURRENT="$BACKOFF_BASE"
                    else
                        log_msg "DNS Engine down (5354/UDP) — calling ensure_running..."

                        watchdog_api_call "ensure_running"
                        RC=$?

                        case "$RC" in
                            0)
                                log_msg "DNS restart succeeded"
                                DNS_BACKOFF_CURRENT="$BACKOFF_BASE"
                                ;;
                            3)
                                # rate-limited — extra backoff
                                DNS_BACKOFF_CURRENT=$((DNS_BACKOFF_CURRENT * 2))
                                [ "$DNS_BACKOFF_CURRENT" -gt "$BACKOFF_MAX" ] && DNS_BACKOFF_CURRENT="$BACKOFF_MAX"
                                log_msg "WARNING: rate-limited — next attempt in ${DNS_BACKOFF_CURRENT}s"
                                ;;
                            *)
                                DNS_BACKOFF_CURRENT=$((DNS_BACKOFF_CURRENT * 2))
                                [ "$DNS_BACKOFF_CURRENT" -gt "$BACKOFF_MAX" ] && DNS_BACKOFF_CURRENT="$BACKOFF_MAX"
                                log_msg "WARNING: DNS restart failed (rc=$RC) — next attempt in ${DNS_BACKOFF_CURRENT}s"
                                ;;
                        esac
                    fi
                else
                    # DNS is running — reset backoff
                    DNS_BACKOFF_CURRENT="$BACKOFF_BASE"
                fi
            fi
        fi
    fi

    # --- [13.4] Periodic log every 20 iterations (~10 minutes) ---
    if [ $((LOOP_COUNT % 20)) -eq 0 ]; then
        log_msg "Watchdog alive (loop #$LOOP_COUNT, webui_backoff=${WEBUI_BACKOFF_CURRENT}s, dns_backoff=${DNS_BACKOFF_CURRENT}s)"
    fi
done

# Unreachable (infinite loop)
exit 0