# --- Port check ---
# HARD-WD-02: added `netstat` fallback for older Android builds
# that ship without `ss`.
_wd_is_port_open() {
    local port="$1"
    local proto="${2:-tcp}"
    local hex_port

    case "$port" in
        ''|*[!0-9]*) return 1 ;;
    esac

    hex_port=$(printf "%04X" "$port" 2>/dev/null) || return 1

    if [ "$proto" = "udp" ]; then
        if [ -f /proc/net/udp ] && grep -qi ":$hex_port " /proc/net/udp 2>/dev/null; then
            return 0
        fi
        if [ -f /proc/net/udp6 ] && grep -qi ":$hex_port " /proc/net/udp6 2>/dev/null; then
            return 0
        fi
        if command -v ss >/dev/null 2>&1; then
            ss -lun 2>/dev/null | grep -q ":$port " && return 0
        elif command -v netstat >/dev/null 2>&1; then
            netstat -uln 2>/dev/null | grep -q ":$port " && return 0
        fi
    else
        if [ -f /proc/net/tcp ] && grep -qi ":$hex_port " /proc/net/tcp 2>/dev/null; then
            return 0
        fi
        if [ -f /proc/net/tcp6 ] && grep -qi ":$hex_port " /proc/net/tcp6 2>/dev/null; then
            return 0
        fi
        if command -v ss >/dev/null 2>&1; then
            ss -ltn 2>/dev/null | grep -q ":$port " && return 0
        elif command -v netstat >/dev/null 2>&1; then
            netstat -tln 2>/dev/null | grep -q ":$port " && return 0
        fi
    fi

    return 1
}

# --- WebUI cleanup ---
_wd_cleanup_webui() {
    pkill -9 -x dnscrypt-webui 2>/dev/null
    rm -f "$RUN_DIR/webui.pid" 2>/dev/null
    rm -f /data/local/tmp/webui.pid 2>/dev/null
}

# --- Start WebUI ---
# ⚠️ PRECONDITION (M-2 fix): the caller MUST have already
# ensured that no previous WebUI instance is running. The
# canonical way to do so is `_wd_cleanup_webui`. This function
# deliberately does NOT call it, so that its side effects
# (kill -9, PID-file removal) remain visible at the call site
# in section [13.2] and are not hidden inside a "start" helper.
_wd_start_webui() {
    local bin="$1"
    local port="$2"

    log_msg "Starting WebUI (port: $port)"

    export HOME=/data/local/tmp

    if command -v setsid >/dev/null 2>&1; then
        setsid env HOME="$HOME" "$bin" >/dev/null 2>&1 < /dev/null &
    elif command -v busybox >/dev/null 2>&1 && busybox --list 2>/dev/null | grep -q setsid; then
        busybox setsid env HOME="$HOME" "$bin" >/dev/null 2>&1 < /dev/null &
    else
        nohup env HOME="$HOME" "$bin" >/dev/null 2>&1 < /dev/null &
    fi

    sleep 1
    local web_pid=""
    web_pid=$(pgrep -x "dnscrypt-webui" 2>/dev/null | head -n1)

    if [ -n "$web_pid" ]; then
        printf "%d\n" "$web_pid" > "${RUN_DIR}/webui.pid.tmp" 2>/dev/null
        mv -f "${RUN_DIR}/webui.pid.tmp" "${RUN_DIR}/webui.pid" 2>/dev/null
    fi

    local i=0
    while [ "$i" -lt 35 ]; do
        if [ -n "$web_pid" ] && ! kill -0 "$web_pid" 2>/dev/null; then
            log_msg "ERROR: WebUI process died (Port collision?)"
            return 1
        fi
        if _wd_is_port_open "$port" tcp; then
            log_msg "WebUI bound to port $port (PID: ${web_pid:-unknown})"
            return 0
        fi
        sleep 1
        i=$((i + 1))
    done

    log_msg "ERROR: WebUI failed to bind within 35s"
    return 1
}

# --- Read profile memory hint (v1.1.0, self-contained) ---
#
# Returns a user-facing string describing the expected soft
# memory limit for the active profile.
#
# ⚠️ This is a HINT only. main.go is the authority.
#
# Uses the same table as:
#   • functions.sh:get_profile_memory_hint
#   • main.go:memoryLimitForProfile
#   • customize.sh [21]
#
# Table:
#   light    →  80 MB
#   normal   → 100 MB
#   pro      → 120 MB
#   proplus  → 160 MB
#   ultimate → 220 MB
_wd_get_profile_memory_hint() {
    local profile="pro"

    if [ -f "$SELECTED_PROFILE_FILE" ]; then
        local p
        p=$(cat "$SELECTED_PROFILE_FILE" 2>/dev/null | tr -d '\r\n ')
        case "$p" in
            light|normal|pro|proplus|ultimate) profile="$p" ;;
        esac
    fi

    local mb
    case "$profile" in
        light)    mb="80"  ;;
        normal)   mb="100" ;;
        pro)      mb="120" ;;
        proplus)  mb="160" ;;
        ultimate) mb="220" ;;
        *)        mb="80"  ;;
    esac

    printf "%s MB (%s)" "$mb" "$profile"
}

# ============================================================
# [8] Read credentials — section-restricted (fallback auth)
# ============================================================
# Reads ONLY from [monitoring_ui]. Section tracking ignores any
# username/password in other sections.
#
# This is used ONLY as a fallback when the watchdog token file
# is not available (see WD-TOKEN fix). With the token file in
# place, the Basic Auth header is not sent.
# ============================================================
WATCH_USER=""
WATCH_PASS=""
HAS_CREDS=0

if [ -f "$TOML_FILE" ]; then
    in_section=0
    while IFS= read -r line || [ -n "$line" ]; do
        line=$(printf '%s' "$line" | tr -d '\r')
        trimmed=$(printf '%s' "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')

        case "$trimmed" in
            ''|\#*) continue ;;
        esac

        case "$trimmed" in
            \[*)
                section=$(printf '%s' "$trimmed" | sed 's/^\[\([^]]*\)\].*$/\1/')
                section=$(printf '%s' "$section" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')

                if [ "$section" = "monitoring_ui" ]; then
                    in_section=1
                else
                    in_section=0
                fi
                continue
                ;;
        esac

        [ "$in_section" = "0" ] && continue

        case "$trimmed" in
            *=*)
                key=$(printf '%s' "$trimmed" | sed 's/^\([^=]*\)=.*/\1/')
                key=$(printf '%s' "$key" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')

                val=$(printf '%s' "$trimmed" | sed 's/^[^=]*=//')
                val=$(printf '%s' "$val" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
                case "$val" in
                    *" #"*) val="${val%% #*}" ;;
                esac
                val=$(printf '%s' "$val" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
                val=$(printf '%s' "$val" | sed "s/^['\"]//;s/['\"]$//")

                case "$key" in
                    username) WATCH_USER="$val" ;;
                    password) WATCH_PASS="$val" ;;
                esac
                ;;
        esac
    done < "$TOML_FILE"
fi

if [ -n "$WATCH_USER" ] && [ -n "$WATCH_PASS" ]; then
    log_msg "Fallback credentials loaded from [monitoring_ui]"
    HAS_CREDS=1
else
    log_msg "No fallback credentials in [monitoring_ui] (token-only mode)"
    HAS_CREDS=0
fi

