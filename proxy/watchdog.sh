#!/system/bin/sh
# ============================================================
# DNSCrypt Smart Filter – watchdog.sh
# Version: v1.2.0 (Global Edition)
# Author: gasciljh
# Repository: https://github.com/gasciljh/dnscrypt-proxy-webui
# ============================================================
# Purpose:
#   Standalone watchdog process that monitors the WebUI and the
#   DNS Engine and restarts them when needed.
#
#   The watchdog is launched by service.sh as an independent
#   process (nohup + background), so that $$ inside this file
#   refers to the real watchdog PID, not service.sh's.
#
# Responsibilities:
#   • Monitor the WebUI (TCP port) and restart it if closed
#   • Monitor the DNS Engine (5354/UDP) and restart it via the
#     main.go API (POST /api/ensure_running_service)
#   • Respect STATUS_FILE as "user intent":
#       ON  → restart DNS if crashed
#       OFF → do nothing (user stopped it manually)
#   • Exponential backoff (30s → 600s max) per service
#   • Reset backoff on success and on STATUS_FILE change
#   • Handle HTTP 429 (rate limit) with additional backoff
#   • Exit cleanly when the disable file is present
#
# Arguments (in order):
#   1. WATCHDOG_PID_FILE   — path to the watchdog PID file
#   2. MODDIR              — module directory
#   3. PORT                — WebUI port (TCP)
#   4. AUTO_RESTART_DNS    — "0" or "1"
#   5. AUTO_RESTART_WEBUI  — "0" or "1"
#
# Authentication (v1.2.0 — Global Edition):
#   watchdog_api_call() authenticates to
#   POST /api/ensure_running_service using, in order of
#   preference:
#
#     1. X-Watchdog-Token header  ← preferred
#        The token is generated by:
#          • customize.sh  §[19b] (during install), or
#          • main.go       loadOrCreateWatchdogToken() (first
#                           WebUI startup, if the installer
#                           did not create one).
#        It is read from: $RUN_DIR/.watchdog_token (mode 0600).
#
#     2. Authorization: Basic <user:pass>  ← fallback
#        Read from [monitoring_ui] in dnscrypt-proxy.toml.
#        Used only when the token file is missing or empty.
#
#   The token path is preferred because it is:
#     • Independent of the credentials file.
#     • Constant-time-compared in main.go (subtle.ConstantTimeCompare).
#     • Localhost-scoped (main.go still checks isLocalRequest).
#     • Not subject to the login rate limiter (5 attempts / 15 min).
#
# API call:
#   Uses POST /api/ensure_running_service (CSRF-GET protection).
#   Return codes:
#     0 — success (2xx)
#     1 — no HTTP client available
#     2 — network/timeout failure
#     3 — 429 rate-limited
#     4 — other HTTP error, OR unable to determine the result
#
# v1.1.0 additions (kept):
#   • Logs the active profile + expected memory hint at startup
#     (self-contained — does not depend on functions.sh)
#   • Structured startup banner with profile context
#   • All messages are English (global release)
#
# v1.2.0 additions:
#   • Watchdog token authentication (see above).
#   • Explicit note: this script does NOT participate in the
#     v1.2.0 data-preservation layers. Its sole responsibility
#     is restarting services.
#   • Startup diagnostics block ([5b]) that logs (read-only):
#       - Number of available snapshots
#       - Content of .last_stable
#       - Content of .pending_notification (if any)
#       - Number of in-flight + orphan transaction dirs
#   • Shutdown messages distinguish SIGTERM, SIGINT, SIGQUIT.
#   • Startup banner is structured into sections
#     (Config / Paths / Auth / Data Preservation).
#   • All messages are English-only (global edition).
#
# ============================================================
# v1.2.0 — POST-AUDIT FIXES, ROUND 1 (kept)
# ============================================================
# A pre-release audit of this file identified the following
# issues. All of them are addressed in-place; no version bump.
#
#   🔧 BUG-A (critical) — The `watchdog_api_call` function wrote
#     curl's HTTP status code to a file under `/tmp/`. On modern
#     Android, `/tmp` is NOT guaranteed to exist. When the
#     redirect failed, `http_code` stayed empty and the function
#     fell through to "success" — defeating the watchdog's
#     primary purpose.
#
#     Fix: all temporary files now live under `$RUN_DIR`.
#
#   🔧 BUG-B — An empty `http_code` was still treated as
#     success. This is undecidable: it can mean a truncated
#     response, a proxy injecting garbage, or an ancient curl
#     that does not support -w.
#
#     Fix: return 4 (other HTTP error) when http_code is empty.
#
#   🔧 BUG-C — `PORT` was only checked for emptiness. A
#     non-numeric value would cause an infinite restart loop.
#
#     Fix: validate PORT is a positive integer in [1, 65535];
#     fall back to 9090 otherwise.
#
#   🔧 WD-1 — A `{ ... } 2>/dev/null` block around the profile
#     memory hint call was a no-op. Removed.
#
#   🔧 WD-2 — The comment above the backoff constants said
#     "Reset when STATUS_FILE changes" without qualifying that
#     this applies ONLY to DNS_BACKOFF_CURRENT. Clarified.
#
#   🔧 WD-3 — Argument validation only checked $1 and $2.
#     Now it also validates the total argument count and the
#     numeric nature of $3 (PORT).
#
#   🔧 WD-TOKEN (critical) — Watchdog now sends
#     the X-Watchdog-Token header. See the "Authentication"
#     block above for the full server-side contract.
#
# ============================================================
# v1.2.0 — POST-AUDIT FIXES, ROUND 2 (this revision)
# ============================================================
# A second independent audit of this file identified the
# following issues. All are fixed in-place; no version bump.
#
#   🔧 M-4 (CRITICAL) — The wget/busybox fallback paths in
#     `watchdog_api_call` used `-qO-`, which does NOT print
#     HTTP response headers. As a result, `http_code` was
#     ALWAYS empty in those paths, and the BUG-B fix (empty
#     code → return 4) turned every SUCCESSFUL restart over
#     wget/busybox into a "failure". This caused an infinite
#     retry loop with growing backoff — precisely on the
#     ancient devices where curl is missing.
#
#     Fix: for wget/busybox, rely on the process exit code:
#       • 0 → 2xx success
#       • 8 → HTTP error (GNU wget only) → return 4
#       • any other non-zero → network/timeout → return 2
#     A 429 cannot be distinguished in this path; it will be
#     treated as a generic failure (return 2 or 4), which is
#     acceptable because the backoff is applied anyway.
#
#   🔧 M-2 — `_wd_cleanup_webui` was called TWICE when
#     restarting the WebUI: once in section [13.2] and once
#     inside `_wd_start_webui`. The inner call has been
#     removed; `_wd_start_webui` now documents the
#     precondition that no prior instance must be running.
#
#   🔧 M-3 — `wd_token=$(_wd_get_watchdog_token 2>/dev/null
#     || echo "")` was over-defensive. The helper writes
#     nothing to stderr, and its failure mode is "empty
#     stdout", not a non-zero exit that aborts the caller.
#     Simplified to `|| :` (explicit no-op) for readability.
#
#   🔧 M-5 / M-6 — Section [5b] duplicated the token-
#     validation logic instead of reusing
#     `_wd_get_watchdog_token`. Any future change to the token
#     contract would have required editing two places. The
#     helper has been MOVED to section [2b] (before [3]) so it
#     is available to [5b], and [5b] now calls it.
#
#   🔧 M-1 — The case pattern `sh|ash|bash|busybox|*sh` was
#     redundant: `*sh` already covers sh/ash/bash. Collapsed
#     to `busybox|*sh`.
#
#   🔧 L-1 / L-2 — The argument-count check accepted
#     `$# >= 5` and silently ignored extra arguments. It now
#     requires EXACTLY 5 arguments, and the error message has
#     been reworded accordingly.
#
#   🔧 L-3 — The duplicate-instance guard used `kill -0`,
#     which returns 0 for zombie processes. A zombie watchdog
#     from a previous boot could therefore block the new
#     instance forever. The guard now also inspects
#     /proc/PID/stat and treats state 'Z' as "not running".
#
# ============================================================
# Coordination with v1.2.0 data-preservation layers:
# ============================================================
#   watchdog.sh does NOT participate in any of the layers
#   listed below. It runs continuously in the background and
#   only restarts the WebUI / DNS engine when they become
#   unavailable.
#
#   The persistent backup directory is never touched by this
#   script — even when services restart (which is the normal
#   behaviour of a watchdog and not a data-critical event).
#
#   The startup diagnostics block ([5b]) is READ-ONLY.
#
#   Layer table:
#     1  — Multi-source detection   — customize.sh
#     2  — Persistent backup        — service.sh + main.go
#     3  — Integrity verification   — customize.sh
#     4  — Transactional upgrades   — customize.sh
#     5  — Root-solution compat     — customize.sh
#     6  — SELinux preservation     — customize.sh
#     7  — Recovery mode            — customize.sh
#     8  — Config migrations        — customize.sh
#     9  — Automation + rotation    — service.sh
#     10 — Observability            — status.sh --diagnose
#
# ============================================================
# POSIX note on `local`:
#   This script uses `local` for all internal variables. The
#   `local` keyword is supported by:
#     • mksh (the default /system/bin/sh on modern Android)
#     • busybox ash (older Android)
#     • bash, dash, ksh
#   It is NOT part of the POSIX sh standard, but every shell
#   Android ships supports it.
# ============================================================

# v1.2.0: --version flag (checked before any argument parsing)
case "${1:-}" in
	--version)
		echo "$0: v1.2.0"
		exit 0
		;;
esac

export PATH=/sbin:/system/bin:/system/xbin:/vendor/bin:/data/adb/magisk:/data/adb/ksu/bin:/data/adb/ap/bin:$PATH

# ============================================================
# [1] Parse arguments
# ============================================================
# L-1 / L-2 fix: require EXACTLY 5 arguments. Fewer means the
# caller is broken; more means the caller expects an interface
# that does not exist. In both cases, fail fast with a clear
# message rather than silently ignoring the extras.
if [ "$#" -ne 5 ]; then
    echo "watchdog.sh: requires exactly 5 arguments, got $#" >&2
    echo "Usage: watchdog.sh <pid_file> <moddir> <port> <auto_dns> <auto_webui>" >&2
    exit 1
fi

WATCHDOG_PID_FILE="$1"
MODDIR="$2"
PORT="$3"
AUTO_RESTART_DNS="$4"
AUTO_RESTART_WEBUI="$5"

# --- Validate required args ---
if [ -z "$WATCHDOG_PID_FILE" ] || [ -z "$MODDIR" ]; then
    echo "watchdog.sh: missing required args" >&2
    echo "Usage: watchdog.sh <pid_file> <moddir> <port> <auto_dns> <auto_webui>" >&2
    exit 1
fi

if [ ! -d "$MODDIR" ]; then
    echo "watchdog.sh: MODDIR not found: $MODDIR" >&2
    exit 1
fi

# --- BUG-C fix: validate PORT is a positive integer ---
if ! echo "$PORT" | grep -qE '^[0-9]+$' || [ "$PORT" -lt 1 ] || [ "$PORT" -gt 65535 ]; then
    PORT="9090"
fi

[ -z "$AUTO_RESTART_DNS" ]   && AUTO_RESTART_DNS="1"
[ -z "$AUTO_RESTART_WEBUI" ] && AUTO_RESTART_WEBUI="1"

case "$AUTO_RESTART_DNS"   in 0|1) ;; *) AUTO_RESTART_DNS="1"   ;; esac
case "$AUTO_RESTART_WEBUI" in 0|1) ;; *) AUTO_RESTART_WEBUI="1" ;; esac

# --- Validate WEBUI binary ---
WEBUI="$MODDIR/proxy/dnscrypt-webui"
if [ ! -f "$WEBUI" ]; then
    echo "watchdog.sh: WEBUI binary not found: $WEBUI" >&2
    exit 1
fi

# ============================================================
# [2] Paths
# ============================================================
LOG_FILE="/data/local/tmp/dnscrypt_main.log"
RUN_DIR="$MODDIR/proxy/run"
STATUS_FILE="$RUN_DIR/dnscrypt.status"
TOML_FILE="$MODDIR/proxy/dnscrypt-proxy.toml"
SELECTED_PROFILE_FILE="$MODDIR/proxy/selected_profile.txt"

# --- v1.2.0 — Watchdog token (WD-TOKEN fix) ---
WATCHDOG_TOKEN_FILE="$RUN_DIR/.watchdog_token"

# --- v1.2.0 — Data preservation paths (READ-ONLY access) ---
PERSISTENT_BACKUP="/sdcard/dnscrypt-webui-backup"
LAST_STABLE_FILE="$PERSISTENT_BACKUP/.last_stable"
PENDING_NOTIFY_FILE="$PERSISTENT_BACKUP/.pending_notification"
USER_FILES="webui.conf dnscrypt-proxy.toml selected_profile.txt allowlist.txt denylist.txt"

# Fallback if run/ is not writable
if [ ! -d "$RUN_DIR" ] || [ ! -w "$RUN_DIR" ]; then
    RUN_DIR="/data/local/tmp"
    STATUS_FILE="/data/local/tmp/dnscrypt.status"
    WATCHDOG_TOKEN_FILE="/data/local/tmp/.watchdog_token"
fi

# ============================================================
# [2b] Watchdog token reader (WD-TOKEN / M-5 / M-6 fix)
# ============================================================
# MOVED HERE (previously section [7b]) so that section [5b]
# can reuse it instead of duplicating the validation logic.
#
# Reads the token file written by customize.sh §[19b] (during
# install) or by main.go loadOrCreateWatchdogToken() (first
# WebUI startup). The token is sent as the X-Watchdog-Token
# header in `watchdog_api_call`.
#
# File location:
#   $RUN_DIR/.watchdog_token  (mode 0600, 64 hex chars)
#
# The token is re-read on EVERY API call (not cached) because:
#   • Reads are cheap (one file, 64 bytes).
#   • main.go may regenerate the token if the file is missing
#     on first startup — a cached empty value would then stay
#     empty forever.
#   • A rotated token (unlikely but possible) is picked up
#     without a watchdog restart.
#
# Return values:
#   0 — token read and looks valid (>= 32 chars); printed to stdout
#   1 — token file missing, empty, or too short
#
# This helper is deliberately self-contained (not sourced from
# functions.sh) because watchdog.sh must run even when
# functions.sh is missing or unreadable.
# ============================================================
_wd_get_watchdog_token() {
    [ -f "$WATCHDOG_TOKEN_FILE" ] || return 1

    local tok
    tok=$(cat "$WATCHDOG_TOKEN_FILE" 2>/dev/null | tr -d '\r\n ')

    [ -n "$tok" ] || return 1
    [ "${#tok}" -ge 32 ] || return 1

    printf "%s" "$tok"
    return 0
}

# ============================================================
# [3] log_msg
# ============================================================
# HARD-WD-03: emergency-only rotation at 50 MB, every 100th
# call. Mirrors functions.sh:log_fn. The counter is a global
# by design (it must persist across calls).
_LOG_CALL_COUNT=0

log_msg() {
    _LOG_CALL_COUNT=$((_LOG_CALL_COUNT + 1))

    if [ $((_LOG_CALL_COUNT % 100)) -eq 0 ] && [ -f "$LOG_FILE" ]; then
        local _size
        _size=$(wc -c < "$LOG_FILE" 2>/dev/null | tr -d ' ')
        if [ -n "$_size" ] && [ "$_size" -gt 52428800 ]; then
            local _emg="${LOG_FILE}.emergency.$(date +%s)"
            mv -f "$LOG_FILE" "$_emg" 2>/dev/null
            : > "$LOG_FILE"
        fi
    fi

    echo "$(date +'%Y-%m-%d %H:%M:%S') - [watchdog] $1" >> "$LOG_FILE" 2>/dev/null
}

# ============================================================
# [4] Prevent duplicate watchdog instances
# ============================================================
# M-1 fix: `*sh` already matches sh/ash/bash; only busybox
# needs an explicit alternative. The pattern list has been
# collapsed for clarity.
#
# L-3 fix: `kill -0` returns 0 for zombies. A zombie watchdog
# from a previous boot would block the new instance forever.
# We now also inspect /proc/PID/stat and reject state 'Z'.
# ============================================================
if [ -f "$WATCHDOG_PID_FILE" ]; then
    old_pid=$(cat "$WATCHDOG_PID_FILE" 2>/dev/null | tr -d '\r\n ')
    if [ -n "$old_pid" ] && [ -d "/proc/$old_pid" ]; then
        # L-3: reject zombies. awk is safe here because `comm`
        # for shell processes never contains spaces (the kernel
        # truncates it to 15 chars and replaces problematic
        # characters).
        old_state=$(awk '{print $3}' "/proc/$old_pid/stat" 2>/dev/null)

        if [ "$old_state" = "Z" ]; then
            log_msg "PID $old_pid is a zombie (stale PID file) — ignoring"
        else
            old_comm=$(cat "/proc/$old_pid/comm" 2>/dev/null)
            case "$old_comm" in
                busybox|*sh)
                    log_msg "Watchdog already running (PID: $old_pid), exiting"
                    exit 0
                    ;;
                *)
                    log_msg "PID $old_pid was reused by '$old_comm', ignoring"
                    ;;
            esac
        fi
    fi
fi

# ============================================================
# [5] Write real PID
# ============================================================
# We run as an independent process (not a subshell).
# $$ = this process's PID = real watchdog PID.
#
# HARD-WD-04: explicit error check. A failed write would leave
# the script running without a PID file, defeating the
# duplicate-instance guard in section [4] on the next boot.
# ============================================================
if ! printf "%d\n" $$ > "${WATCHDOG_PID_FILE}.tmp" 2>/dev/null; then
    log_msg "FATAL: cannot write PID tmp file: ${WATCHDOG_PID_FILE}.tmp"
    exit 1
fi
if ! mv -f "${WATCHDOG_PID_FILE}.tmp" "$WATCHDOG_PID_FILE" 2>/dev/null; then
    log_msg "FATAL: cannot move PID file into place: $WATCHDOG_PID_FILE"
    rm -f "${WATCHDOG_PID_FILE}.tmp" 2>/dev/null
    exit 1
fi

# ============================================================
# [5b] v1.2.0 — Startup diagnostics (READ-ONLY)
# ============================================================
# Logs a structured snapshot of the module state at watchdog
# startup. This makes the boot log a complete picture without
# requiring the user to run status.sh manually.
#
# ⚠️ READ-ONLY: This block inspects the backup directory but
#    does NOT create, modify, or delete any files.
# ============================================================

# --- Read pending notification (if any) ---
_pending_msg=""
if [ -f "$PENDING_NOTIFY_FILE" ]; then
    _pending_msg=$(cat "$PENDING_NOTIFY_FILE" 2>/dev/null | tr -d '\r\n ')
fi

# --- Read .last_stable (if any) ---
_last_stable=""
if [ -f "$LAST_STABLE_FILE" ]; then
    _last_stable=$(cat "$LAST_STABLE_FILE" 2>/dev/null | tr -d '\r\n ')
fi

# --- Count available snapshots ---
_snap_count=0
if [ -d "$PERSISTENT_BACKUP" ]; then
    _snap_count=$(cd "$PERSISTENT_BACKUP" 2>/dev/null && \
        ls -1d */ 2>/dev/null | \
        sed 's:/$::' | \
        grep -E '^[0-9]{8}-[0-9]{6}-' | \
        wc -l | tr -d ' ')
    [ -z "$_snap_count" ] && _snap_count=0
fi

# --- Count in-flight transactions (txn-*) ---
_txn_count=0
if [ -d "$PERSISTENT_BACKUP" ]; then
    _txn_count=$(cd "$PERSISTENT_BACKUP" 2>/dev/null && \
        ls -1d txn-*/ 2>/dev/null | \
        wc -l | tr -d ' ')
    [ -z "$_txn_count" ] && _txn_count=0
fi

# --- Count orphan transactions (orphan-txn-*) ---
_orphan_count=0
if [ -d "$PERSISTENT_BACKUP" ]; then
    _orphan_count=$(cd "$PERSISTENT_BACKUP" 2>/dev/null && \
        ls -1d orphan-txn-*/ 2>/dev/null | \
        wc -l | tr -d ' ')
    [ -z "$_orphan_count" ] && _orphan_count=0
fi

# --- Check whether the watchdog token file exists ---
# M-5 / M-6 fix: delegate to the canonical helper instead of
# duplicating the ">= 32 chars" validation here. A single
# source of truth for the token contract.
_token_present="no"
if _wd_get_watchdog_token >/dev/null 2>&1; then
    _token_present="yes"
fi

# ============================================================
# [5c] Startup banner (structured)
# ============================================================
log_msg "============================================"
log_msg "Watchdog started (PID: $$)"
log_msg "   Version: v1.2.0 (Global Edition)"
log_msg "─── Config ───"
log_msg "   MODDIR:     $MODDIR"
log_msg "   PORT:       $PORT"
log_msg "   Auto-DNS:   $AUTO_RESTART_DNS"
log_msg "   Auto-WebUI: $AUTO_RESTART_WEBUI"
log_msg "─── Paths ───"
log_msg "   RUN_DIR:    $RUN_DIR"
log_msg "   STATUS_FILE: $STATUS_FILE"
log_msg "─── Auth ───"
log_msg "   Token file: $WATCHDOG_TOKEN_FILE"
log_msg "   Token ready: $_token_present"
log_msg "─── Data Preservation (READ-ONLY) ───"
log_msg "   Snapshot dir:   $PERSISTENT_BACKUP"
log_msg "   Snapshots:      $_snap_count"
log_msg "   In-flight txn:  $_txn_count"
log_msg "   Orphan txn:     $_orphan_count"
if [ -n "$_last_stable" ]; then
    log_msg "   Last stable:    $_last_stable"
else
    log_msg "   Last stable:    (none yet)"
fi
if [ -n "$_pending_msg" ]; then
    log_msg "   Notification:   $_pending_msg"
    log_msg "   (main.go will log and delete this at startup)"
fi
log_msg "   Note: this script does NOT touch the backup directory."
log_msg "============================================"

